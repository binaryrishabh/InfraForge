import { expect, test } from "bun:test";
import { learningContent as content } from "../learning/content";
import { REVIEWED_CHALLENGES } from "../learning/reviewedChallenges";
import { CHALLENGE_VERSIONS } from "../challenges/definitions";
import { REGISTRY, specHash } from "../challenges/registry";

const rank: Record<string, number> = {beginner: 0, intermediate: 1, advanced: 2};
const dupes = (list: string[]) => list.filter((x, i) => list.indexOf(x) !== i);
const byId = new Map(content.lessons.map(l => [l.id, l]));
/** "lesson->prerequisite" pairs that already pointed at a higher-level lesson in published content at base commit 46f8a9f.
 *  Generated by running this same check on that commit's lessons: there were none. Add nothing here for new lessons. */
const GRANDFATHERED_PREREQUISITES: readonly string[] = [];
/** Reviewed pins that intentionally have no lab lesson. Empty: every reviewed challenge is taught by a lab. */
const PINS_WITHOUT_LESSON: readonly string[] = [];

test("every lesson id is registered exactly once in the flat list and in exactly one module", () => {
  expect(dupes(content.lessons.map(l => l.id))).toEqual([]);
  const listed = content.tracks.flatMap(t => t.modules.flatMap(m => m.lessonIds));
  expect(dupes(listed)).toEqual([]);
  expect(content.lessons.map(l => l.id).filter(id => !listed.includes(id))).toEqual([]);
  expect(listed.filter(id => !byId.has(id))).toEqual([]);
  for (const l of content.lessons) {
    const owner = content.tracks.find(t => t.id === l.trackId)?.modules.find(m => m.id === l.moduleId);
    expect(owner?.lessonIds.includes(l.id), `${l.id} is listed in its own track and module`).toBe(true);
  }
});

test("every module appears once in exactly one track and track ids are unique", () => {
  expect(dupes(content.tracks.map(t => t.id))).toEqual([]);
  for (const t of content.tracks) expect(dupes(t.modules.map(m => m.id)), `module ids in ${t.id}`).toEqual([]);
  const identities = content.tracks.flatMap(t => t.modules.map(m => `${t.id}/${m.id}`));
  expect(dupes(identities)).toEqual([]);
});

test("challenge definitions are unique and every lab references an existing latest challenge with a matching reviewed pin", () => {
  expect(dupes(CHALLENGE_VERSIONS.map(d => `${d.id}@${d.version}`))).toEqual([]);
  for (const lab of content.lessons.filter(l => l.kind === "executable-lab")) {
    const id = (lab as { experiment: { challengeId: string } }).experiment.challengeId, latest = REGISTRY.latest(id);
    expect(latest, `${lab.id} challenge ${id} exists`).toBeTruthy();
    // Reviewed pins are keyed by lesson id and contentVersion (old versions keep their own record).
    const pin = REVIEWED_CHALLENGES[`${lab.id}@${lab.contentVersion}`];
    expect(pin, `${lab.id} has a reviewed pin for its current content version`).toBeTruthy();
    expect([pin!.challengeId, pin!.version], `${lab.id} pin names the latest challenge version`).toEqual([id, latest!.definition.version]);
    expect(pin!.hash, `${id} pin matches its definition`).toBe(specHash(latest!.definition));
  }
  for (const [key, pin] of Object.entries(REVIEWED_CHALLENGES)) {
    expect(REGISTRY.find(pin.challengeId, pin.version), `${key} resolves`).toBeTruthy();
    if (!PINS_WITHOUT_LESSON.includes(key)) {
      const taught = [...content.lessons, ...(content.archivedLessons ?? [])].some(l => l.kind === "executable-lab" && l.experiment.challengeId === pin.challengeId);
      expect(taught, `${key} has a lab lesson`).toBe(true);
    }
  }
});

test("prerequisites exist and never point at a higher-level lesson except grandfathered published pairs; follow-up links resolve", () => {
  const upward: string[] = [];
  for (const l of content.lessons) {
    for (const p of l.prerequisites) {
      const q = byId.get(p);
      expect(q, `${l.id} prerequisite ${p} exists`).toBeTruthy();
      if (q && rank[q.level]! > rank[l.level]!) upward.push(`${l.id}->${p}`);
    }
    for (const m of (l.followUp ?? "").matchAll(/\(([a-z0-9-]+)\)/g)) expect(byId.has(m[1]!), `${l.id} follow-up link (${m[1]})`).toBe(true);
  }
  expect(upward.filter(x => !GRANDFATHERED_PREREQUISITES.includes(x))).toEqual([]);
});
